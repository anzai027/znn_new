function stats = collect(results)
% 保存逐组指标和失败记录。
rows = repmat(struct(),0,1);
for k = 1:numel(results)
    if isempty(results{k}), continue, end
    r = results{k}; j = r.job; m = r.metrics;
    row = struct('id',j.id,'group',j.group,'model',j.model,'example',j.example, ...
        'variant',j.variant,'l',j.l,'noise',j.noise,'seed',j.seed,'scale',j.scale, ...
        'repeat',j.repeat,'gamma',j.gamma,'rates',string(mat2str(j.rates)), ...
        'eps',j.eps,'smooth',j.eps > 0 && ~ismember(j.model,["M1","VFCR"]), ...
        'lambda',j.lambda,'rtol',j.rtol,'atol',j.atol, ...
        'status',r.status,'complete',r.complete,'last',r.last, ...
        'seconds',r.seconds,'calls',r.calls,'tc6',m.tc(1),'tc4',m.tc(2), ...
        'rmse',m.rmse,'rmsed',m.rmsed,'full',m.full,'peak',m.peak,'peakd',m.peakd, ...
        'residual',m.residual,'equality',m.equality,'inequality',m.inequality, ...
        'motion',m.motion.passed,'rate',m.motion.rate,'margin',m.motion.margin, ...
        'lastresidual',m.last,'identifier',r.identifier,'reason',r.reason,'reused',j.reuse ~= "");
    if isempty(rows), rows = row; else, rows(end+1,1) = row; end
end
if isempty(rows), stats = table(); else, stats = struct2table(rows); end
end
