function table0 = collect(results)
% 汇总指标，并保留失败和缺失的区别。
rows = repmat(struct(),0,1);
for k = 1:numel(results)
    if isempty(results{k})
        continue
    end
    r = results{k};
    j = r.job;
    m = r.metrics;
    row = struct('id',j.id,'group',j.group,'example',j.example, ...
        'model',j.model,'port',j.port,'noise',j.noise,'seed',j.seed, ...
        'scale',j.scale,'gamma',j.gamma,'p',j.p,'repeat',j.repeat, ...
        'rtol',j.rtol,'atol',j.atol,'status',r.status,'complete',r.complete, ...
        'last',r.last,'seconds',r.seconds,'calls',r.calls,'steps',m.steps, ...
        'tc6',m.tc(1),'tc4',m.tc(2),'rmse',m.rmse,'rmsed',m.rmsed, ...
        'peak',m.peak,'peakd',m.peakd,'residual',m.residual, ...
        'equality',m.equality,'inequality',m.inequality,'bias',m.bias, ...
        'lastresidual',m.last,'lasterror',m.lastx,'lastdelta',m.lastd, ...
        'lastgradient',m.lastgrad,'sigma',m.min,'smallest',m.smallest, ...
        'tested',m.motion.tested,'motion',m.motion.passed, ...
        'rate',m.motion.rate,'excess',m.motion.excess,'margin',m.motion.margin, ...
        'identifier',r.identifier,'reason',r.reason);
    if isempty(rows)
        rows = row;
    else
        rows(end+1,1) = row;
    end
end
if isempty(rows)
    table0 = table();
else
    table0 = struct2table(rows);
end
end
